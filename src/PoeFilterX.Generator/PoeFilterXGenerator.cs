using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using PoeFilterX.Common;

namespace PoeFilterX.Generator;

[Generator(LanguageNames.CSharp)]
public sealed class PoeFilterXGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider.ForAttributeWithMetadataName(
            OperationModelAttribute.MetadataName,
            static (node, _) => node is RecordDeclarationSyntax,
            static (attribute, _) => Describe((INamedTypeSymbol)attribute.TargetSymbol, attribute.Attributes[0])
        ).WithComparer(EqualityComparer<GeneratorModel>.Default).WithTrackingName("OperationModels");
        var sources = models.Select(static (model, _) => (Name: model.Codec, Source: Emit(model)));
        context.RegisterSourceOutput(sources, static (output, source) =>
            output.AddSource(source.Name + ".g.cs", source.Source));
    }

    private static GeneratorModel Describe(INamedTypeSymbol symbol, AttributeData attribute)
    {
        var properties = symbol.GetMembers().OfType<IPropertySymbol>()
            .Where(property => !property.IsImplicitlyDeclared && !property.IsStatic)
            .Select(DescribeProperty).ToImmutableArray();

        return new GeneratorModel(
            symbol.ContainingNamespace.ToDisplayString(),
            symbol.Name,
            (string)attribute.ConstructorArguments[0].Value!,
            (OperationLanguage)(int)attribute.ConstructorArguments[1].Value!,
            properties
        );
    }

    private static GeneratorProperty DescribeProperty(IPropertySymbol property)
    {
        var metadata = property.GetAttributes().FirstOrDefault(item =>
            item.AttributeClass?.ToDisplayString() == OperationAttribute.MetadataName);
        var values = metadata?.NamedArguments ?? [];

        return new GeneratorProperty(
            property.Name,
            property.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat),
            Value(values, nameof(OperationAttribute.Name), property.Name),
            Value(values, nameof(OperationAttribute.OutputName), property.Name),
            Value(values, nameof(OperationAttribute.Reader), "Read"),
            Value(values, nameof(OperationAttribute.Writer), "Write"),
            Value(values, nameof(OperationAttribute.Target), property.Name),
            Value(values, nameof(OperationAttribute.Minimum), 0),
            Value(values, nameof(OperationAttribute.Maximum), int.MaxValue),
            Value(values, nameof(OperationAttribute.DefaultAlpha), 255),
            Value(values, nameof(OperationAttribute.SkipOutput), false)
        );
    }

    private static T Value<T>(
        ImmutableArray<KeyValuePair<string, TypedConstant>> values,
        string name,
        T fallback
    )
    {
        foreach (var value in values)
        {
            if (value.Key == name)
            {
                return (T)value.Value.Value!;
            }
        }

        return fallback;
    }

    private static string Emit(GeneratorModel model)
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("using System;")
            .AppendLine("using System.Collections.Immutable;")
            .AppendLine("using System.Text;")
            .AppendLine("using PoeFilterX.Engine.Diagnostics;")
            .AppendLine("using PoeFilterX.Engine.Results;")
            .AppendLine("using PoeFilterX.Engine.Checking;");
        code.Append("namespace ").Append(model.Namespace).Append(";\npublic static partial class ")
            .Append(model.Codec).Append("\n{\npublic static ").Append("Result<").Append(model.Name).Append(">")
            .Append(" Parse(string name, ReadOnlySpan<string> args)\n{\nreturn name switch\n{\n");
        foreach (var property in model.Properties)
        {
            code.Append('"').Append(property.Input).Append("\" => ").Append(property.Reader)
                .Append("(default(").Append(property.Type).Append("), args, new OperationReadOptions(\"")
                .Append(property.Input).Append("\", ").Append(property.Minimum).Append(", ")
                .Append(property.Maximum).Append(", ").Append(property.DefaultAlpha)
                .Append(")).Map(static value => new ").Append(model.Name).Append(" { ")
                .Append(property.Name).Append(" = value }),\n");
        }

        code.Append("_ => new ParseError(DiagnosticCodes.UnknownOperation, $\"Unrecognized ")
            .Append(model.Kind == OperationLanguage.Style ? "style command" : "command")
            .Append(" '{name}'\")\n};\n}\npublic static ").Append(model.Name)
            .Append(" Apply(").Append(model.Name).Append(" target, ").Append(model.Name)
            .Append(" patch)\n{\n");
        code.Append("return target with\n{\n");
        foreach (var group in model.Properties.GroupBy(property => property.Target))
        {
            var expression = "target." + group.Key;
            foreach (var property in group)
            {
                expression = "Merge(" + expression + ", patch." + property.Name + ")";
            }

            code.Append(group.Key).Append(" = ").Append(expression).Append(",\n");
        }

        code.Append("};\n}\npublic static void Write(StringBuilder output, ")
            .Append(model.Name).Append(" model)\n{\n");
        foreach (var property in model.Properties.Where(property => !property.SkipOutput))
        {
            code.Append(property.Writer).Append("(output, \"").Append(property.Output)
                .Append("\", model.").Append(property.Target).Append(");\n");
        }

        code.Append("}\npublic static ImmutableArray<OperationDescriptor> Operations { get; } = [\n");
        foreach (var property in model.Properties)
        {
            code.Append("new(\"").Append(property.Input).Append("\", \"").Append(property.Type)
                .Append("\", \"").Append(property.Reader).Append("\", ").Append(property.Minimum)
                .Append(", ").Append(property.Maximum).Append("),\n");
        }

        code.Append("];\n");
        if (model.Kind == OperationLanguage.Style)
        {
            code.Append("public static void Inspect(").Append(model.Name)
                .Append(" model, StyleContributionCollector collector)\n{\n");
            foreach (var target in model.Properties.Select(property => property.Target).Distinct())
            {
                code.Append("collector.Add(\"").Append(target).Append("\", model.").Append(target).Append(");\n");
            }

            code.Append("}\n}\n");
        }
        else
        {
            var properties = model.Properties.Where(property => !property.SkipOutput).ToArray();
            code.Append("public static void Evaluate(").Append(model.Name)
                .Append(" model, ConditionEvaluator evaluator)\n{\n");
            foreach (var property in properties)
            {
                code.Append("evaluator.Add(FilterFact.").Append(property.Name)
                    .Append(", model.").Append(property.Name).Append(");\n");
            }

            code.Append("}\npublic static Result<ItemFacts> Override(ItemFacts item, FilterFact fact, string text) => fact switch\n{\n");
            foreach (var property in properties)
            {
                code.Append("FilterFact.").Append(property.Name).Append(" => ItemFactOverrides.Set(item, fact, text, default(")
                    .Append(property.Type).Append(")),\n");
            }

            code.Append("_ => new ParseError(DiagnosticCodes.InvalidItem, $\"Invalid item fact '{fact}'.\")\n};\npublic static bool HasConditions(")
                .Append(model.Name).Append(" model) => ")
                .Append(string.Join(" || ", properties.Select(property => "model." + property.Name
                    + (property.Type.StartsWith("ImmutableArray", StringComparison.Ordinal) ? ".Length > 0" : " is not null"))))
                .Append(";\n}\npublic enum FilterFact\n{\n");
            foreach (var property in properties)
            {
                code.Append(property.Name).Append(",\n");
            }

            code.Append("}\n");
        }

        return code.ToString();
    }

}
